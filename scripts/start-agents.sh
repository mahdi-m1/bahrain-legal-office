#!/bin/bash
cd "$(dirname "$0")/.."
export CLAUDE_CODE_EXPERIMENTAL_AGENT_TEAMS=1
export TEAMMATE_MODE=tmux

PROMPT=$(cat << 'EOP'
أنشئ فريقاً قانونياً متخصصاً في القانون البحريني يعمل كمكتب استشارات متكامل.

الأدوار:
1. محلل الوثائق: يحلل الملفات في مجلد input/ ويستخرج الوقائع والتواريخ والأطراف.
2. باحث قانوني: يبحث فقط في المصادر الرسمية البحرينية (lloc.gov.bh و ahkam.sjc.bh).
3. كاتب المذكرات: يكتب ملخصات ومذكرات قانونية بأسلوب رسمي بحريني.
4. خبير الطعن: يحلل الأحكام ويقترح أسباب الطعن وفق قانون محكمة التمييز.

القواعد: استخدم فقط المصادر الرسمية المذكورة في CLAUDE.md. اقتبس حرفياً. احفظ النتائج في output/.

ابدأ بفحص مجلد input/.
EOP
)

echo "تشغيل فريق Claude..."
claude -p "$PROMPT"
